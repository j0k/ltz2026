def main():
    with open(os.path.join(OUT, "meta.json"), encoding="utf-8") as f:
        shots = json.load(f)["shots"]
    scenes = []
    for shot, title, text, caption, acts in SCENES:
        actions = [dict(type=t, at=shots[shot][k], **extra) for t, k, extra in acts]
        scenes.append(dict(shot=shot, title=title, text=text, caption=caption, actions=actions))
    film = dict(title="DXA QC — сервис и его возможности", voice="silero:xenia", music="calm", fps=24, captions=True,
                output="dxa_qc_service.mp4", scenes=scenes)
    with open(os.path.join(OUT, "film.json"), "w", encoding="utf-8") as f:
        json.dump(film, f, ensure_ascii=False, indent=1)
    print("сцен:", len(scenes), "символов озвучки:", sum(len(s["text"]) for s in scenes))


if __name__ == "__main__":
    main()
