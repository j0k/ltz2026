def _walk(node: dict, depth: int = 0):
    yield node, depth
    for child in node["children"]:
        yield from _walk(child, depth + 1)


def counts() -> dict:
    """Сколько требований в каждом статусе: считаются узлы со статусом, кроме справки."""
    out = {k: 0 for k in STATUS}
    for node, depth in _walk(TREE):
        if depth and node["status"]:
            out[node["status"]] += 1
    out["total"] = out["done"] + out["partial"] + out["todo"]
    return out


def nodes() -> list[dict]:
    return [n for n, _ in _walk(TREE)]
